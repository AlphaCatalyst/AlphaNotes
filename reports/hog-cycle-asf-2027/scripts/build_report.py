def isna(v):
    return v is None or (isinstance(v, float) and np.isnan(v)) or (isinstance(v, str) and v.strip() == "")


def F(v, f):
    if isna(v):
        return '<span class="na">缺失</span>'
    if isinstance(v, str) and f != "s":
        try:
            v = float(v)
        except ValueError:
            return esc(v)
    try:
        if f == "pct0":
            return f"{v * 100:+.0f}%"
        if f == "pct1":
            return f"{v * 100:+.1f}%"
        if f == "upct0":
            return f"{v * 100:.0f}%"
        if f == "upct1":
            return f"{v * 100:.1f}%"
        if f in ("f0", "f1", "f2", "f3"):
            return f"{float(v):,.{int(f[1])}f}"
        if f == "x1":
            return f"{float(v):.1f}倍"
        if f == "rho":
            return f"{float(v):+.2f}"
    except (TypeError, ValueError):
        pass
    return esc(v)


def tbl(df, spec, cls="", note=None):
    h = "".join(f"<th>{esc(hd)}</th>" for _, hd, _ in spec)
    rows = []
    for _, r in df.iterrows():
        rows.append("<tr>" + "".join(f'<td class="long">{F(r.get(c), "s")}</td>' if f == "long" else f"<td>{F(r.get(c), f)}</td>"
                                     for c, _, f in spec) + "</tr>")
    n = f'<p class="tnote">{note}</p>' if note else ""
    return f'<div class="tw"><table class="{cls}"><thead><tr>{h}</tr></thead><tbody>{"".join(rows)}</tbody></table></div>{n}'



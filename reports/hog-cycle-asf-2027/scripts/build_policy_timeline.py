def norm(s: str) -> str:
    return re.sub(r"\s+", "", s)


def verify():
    bad = 0
    cache = {}
    for e in E:
        u = e["url"]
        try:
            if u not in cache:
                cache[u] = norm(page_text(u))
            ok = norm(e["excerpt"]) in cache[u]
            e["excerpt_verified"] = "是" if ok else "否"
        except Exception as ex:  # noqa: BLE001
            e["excerpt_verified"] = f"未能抓取（{type(ex).__name__}）"
            ok = False
        if not ok:
            bad += 1
            print("FAIL:", e["event_date"], e["title"][:40], u, e["excerpt_verified"])
        if len(e["excerpt"]) > 200:
            print("TOO LONG:", e["title"][:30], len(e["excerpt"]))
    return bad


if __name__ == "__main__":
    nbad = verify()
    E.sort(key=lambda e: e["event_date"][:10])
    with open(OUT / "timeline.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for e in E:
            w.writerow({k: e.get(k, "") for k in FIELDS})
    print(f"wrote {len(E)} rows; excerpt failures: {nbad}")
    sys.exit(0)
